#pragma once

#include "context.hpp"
#include "identity.hpp"
#include "sd_common.hpp"

#include <functional>
#include <future>

#include <sdv/status.hpp>

struct ASDV_ServiceUnitChangeEvent;
struct ASDV_ServiceUnitChangeListenerHandle;

namespace sdv_comms::sd {

// Listeners for changes to service unit registration.

// Change event generated by ServiceUnitChangeListener.
struct ServiceUnitChangeEvent {
    enum class Type { Unknown, Registered, Unregistered, Changed };
    Type event_type;
    ServiceUnitDefinition unit_definition;
};

// ServiceUnitChangeListener
//
// Represents a subscription to updates to service units matching some criteria.
//
// See "CreateBy(Type|Name)*" methods for creation.
//
// An instance of this object manages the lifetime of the subscription.  Call Stop()
// or destroy the instance to terminate the listener.  Note that the listener removal
// will not be complete until the listener callback is invoked with std::nullopt as
// its parameter.
class ServiceUnitChangeListener {
public:
    ServiceUnitChangeListener(ServiceUnitChangeListener&&);
    ~ServiceUnitChangeListener();

    // Stop listening; irreversable.
    void Stop();

    // Returns true if the object holds an active listener handle.
    bool IsValid() const;

    using CreateResult = sdv::SdvResult<ServiceUnitChangeListener>;

    // Repeated callback that will receive notifications of service unit changes
    using ListenerCallback =
            std::function<sdv::SdvStatusCode(std::optional<ServiceUnitChangeEvent>)>;

    // One-time callback to receive result of listener creation, when using Create*Async.
    using CreateCallback = std::function<void(CreateResult)>;

    /**
     * Non-Blocking
     *
     * Create a listener for Service Units matching the given Unit Type.
     *
     * Parameters:
     *    [IN] unit_type: UnitType of desired Service Units.
     *    [IN] listener_cb: Callback to receive notifications of matching service unit changes.
     *    [IN] create_cb: Callback to receive result of the listener creation.
     *
     * Return value:
     *    None; completion_cb will be invoked exactly once with a ServiceUnitChangeListener,
     *    or a non-Ok SdvStatus if an error was encountered.
     */
    static void CreateByTypeAsync(const ctx::Context& context, const UnitType& unit_type,
                                  ListenerCallback listener_cb, CreateCallback create_cb);

    /**
     * Non-Blocking
     *
     * Create a listener for Service Units matching the given Unit Type.
     *
     * Parameters:
     *    [IN] unit_name_args: UnitNameDiscoveryArgs to match Service Units against.
     *    [IN] listener_cb: Callback to receive notifications of matching service unit changes.
     *
     * Return value:
     *    A future for an SdvResult containing either a ServiceUnitChangeListener, or a non-OK
     *    SdvStatus if an error was encountered.
     */
    static std::future<CreateResult> CreateByTypeFuture(const ctx::Context& context,
                                                        const UnitType& unit_type,
                                                        ListenerCallback listener_cb);

    /**
     * Blocking.
     *
     * Create a listener for Service Units matching the given Unit Type.
     *
     * Parameters:
     *    [IN] unit_name_args: UnitNameDiscoveryArgs to match Service Units against.
     *    [IN] listener_cb: Callback to receive notifications of matching service unit changes.
     *
     * Return value:
     *    An SdvResult containing either a ServiceUnitChangeListener, or a non-OK SdvStatus
     *    if an error was encountered.
     */
    static CreateResult CreateByType(const ctx::Context& context, const UnitType& unit_type,
                                     ListenerCallback listener_cb);

    /**
     * Non-Blocking
     *
     * Create a listener for Service Units matching the given Unit Name criteria.
     *
     * Parameters:
     *    [IN] unit_name_args: UnitNameDiscoveryArgs to match Service Units against.
     *    [IN] listener_cb: Callback to receive notifications of matching service unit changes.
     *    [IN] create_cb: Callback to receive result of the listener creation.
     *
     * Return value:
     *    None; completion_cb will be invoked exactly once with a ServiceUnitChangeListener,
     *    or a non-Ok SdvStatus if an error was encountered.
     */
    static void CreateByNameAsync(const ctx::Context& context,
                                  const UnitNameDiscoveryArgs& unit_name_args,
                                  ListenerCallback listener_cb, CreateCallback create_cb);

    /**
     * Non-Blocking
     *
     * Create a listener for Service Units matching the given Unit Name criteria.
     *
     * Parameters:
     *    [IN] unit_name_args: UnitNameDiscoveryArgs to match Service Units against.
     *    [IN] listener_cb: Callback to receive notifications of matching service unit changes.
     *
     * Return value:
     *    A future for an SdvResult containing either a ServiceUnitChangeListener, or a non-OK
     *    SdvStatus if an error was encountered.
     */
    static std::future<CreateResult> CreateByNameFuture(const ctx::Context& context,
                                                        const UnitNameDiscoveryArgs& unit_name_args,
                                                        ListenerCallback listener_cb);

    /**
     * Blocking.
     *
     * Create a listener for Service Units matching the given Unit Name criteria.
     *
     * Parameters:
     *    [IN] unit_name_args: UnitNameDiscoveryArgs to match Service Units against.
     *    [IN] listener_cb: Callback to receive notifications of matching service unit changes.
     *
     * Return value:
     *    An SdvResult containing either a ServiceUnitChangeListener, or a non-OK SdvStatus
     *    if an error was encountered.
     */
    static CreateResult CreateByName(const ctx::Context& context,
                                     const UnitNameDiscoveryArgs& unit_name_args,
                                     ListenerCallback listener_cb);

private:
    ServiceUnitChangeListener() = delete;
    ServiceUnitChangeListener(const ctx::Context&, ASDV_ServiceUnitChangeListenerHandle*);

    // Internal implementation for Create*Async methods.
    template <auto AbiFunc, typename... OtherParams>
    static void CreateAsync(const ctx::Context& context, ListenerCallback listener_cb,
                            CreateCallback create_cb, OtherParams... other_params);

    ctx::Context context_;
    ASDV_ServiceUnitChangeListenerHandle* handle_;
};

};  // namespace sdv_comms::sd