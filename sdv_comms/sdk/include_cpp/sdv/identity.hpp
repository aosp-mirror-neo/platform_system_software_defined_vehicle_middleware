// Size of internal record wrapped by ServiceFqin.
// Should (probably) match ASDV_SERVICE_FQIN_MAX_SIZE_BYTES_INCLUDING_NUL.
// TODO(369534765) - Create and autogenerated constant for internal record size.
static const size_t kServiceFqinSize = 256;

/* Describes the Service Fully Qualified Instance Name.
 *
 * This name comprises the following components:
 *   1) SDV VM Name: The SDV VM Instance on which this Service Bundle is
 *          executing.
 *   2) SDV Package Name: The Package Name within which the Service Bundle was
 *          shipped.
 *   3) Service Bundle Name: The Service Bundle Name as declared in the Package
 *          Manifest.
 *   4) Service Instance Name: The Service Instance Name as assigned by the
 *          Orchestrator when the Service Bundle was loaded.
 *
 * All methods of ServiceFqin are non-blocking and thread-safe.
 */
class ServiceFqin {
public:
    // ServiceFqin is copyable.
    ServiceFqin(const ServiceFqin&) = default;

    /**
     * Create a ServiceFqin from its human-readable string representation.
     *
     * Parameters:
     *    [IN] fqin_str: String representation of FQIN to be parsed.
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a ServiceFqin wrapper.
     */
    static SdvResult<ServiceFqin> FromString(const std::string& fqin_str);

    /**
     * Create a ServiceFqin from its component fields.
     *
     * Each component has a length limit, given below; given limits do not
     * include the NUL terminator.
     *
     * Parameters:
     *    [IN] sdv_vm_name: 127 char max.
     *    [IN] sdv_package_name: 31 char max.
     *    [IN] service_bundle_name: 47 character max.
     *    [IN] service_instance_name: Number 47 character max.
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a ServiceFqin wrapper.
     */
    static SdvResult<ServiceFqin> Create(const std::string& sdv_vm_name,
                                         const std::string& sdv_package_name,
                                         const std::string& service_bundle_name,
                                         const std::string& service_instance_name);

    // Equality operator.
    bool operator==(const ServiceFqin& o) const;

    // Produce a string representation of the ServiceFqin.
    // This representation will be suitable for passing to FromString.
    // The return value could be empty in the event of an error.
    std::string ToString() const;

    // Accessors for components.
    std::string_view sdv_vm_name() const;
    std::string_view sdv_package_name() const;
    std::string_view service_bundle_name() const;
    std::string_view service_instance_name() const;

private:
    ServiceFqin();

    // Same size as wrapped internal type.
    unsigned char data_[kServiceFqinSize];
};

// Size of internal record wrapped by ServicePublicKey.
// Should match ASDV_SERVICE_PUBLIC_KEY_SIZE_BYTES.
// TODO(369534765) - Create and autogenerated constant for internal record size.
static const size_t kServicePublicKeySize = 32;

/// A X25519 Public Key that is used for SDV Service authentication.
struct ServicePublicKey {
    // Equality operator
    bool operator==(const ServicePublicKey& o) const;

    unsigned char data[kServicePublicKeySize];
};

// Size of internal record wrapped by ServiceIdentity.
// TODO(369534765) - Create and autogenerated constant for internal record size.
static const size_t kServiceIdentitySize = 296;

/* Defines the Service Identity of a Service Bundle.
 * The Identity of a Service Bundle consists of three components:
 *   1) SID (Service Identifier): A vehicle wide unique 64 bit number assigned to the running
 *          instance of the Service Bundle.
 *   2) FQIN (Fully Qualified Instance Name): The full human readable name of the running instance
 *          of the Service Bundle.
 *   3) PublicKey: The X5509 Public Key corresponding to the Private Key held by the running
 *          instance of the Service Bundle.
 */
class ServiceIdentity {
public:
    // Copyable.
    ServiceIdentity(const ServiceIdentity&) = default;

    /**
     * Create a ServiceIdentity from its component fields.
     *
     * Parameters:
     *    [IN] sid
     *    [IN] fqin
     *    [IN] public_key
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a ServiceIdentity wrapper.
     */
    static SdvResult<ServiceIdentity> Create(unsigned long sid, const ServiceFqin& fqin,
                                             const ServicePublicKey& public_key);

    // Equality operator
    bool operator==(const ServiceIdentity& o) const;

    // Accessor for SID.
    unsigned long sid() const;

    // Accessor for contained ServiceFqin.
    // Returned reference has same lifetime as the ServiceIdentity.
    const ServiceFqin& fqin() const;

    // Accessor for contained ServicePublicKey.
    // Returned reference has same lifetime as the ServiceIdentity.
    const ServicePublicKey& public_key() const;

private:
    friend class sd::ServiceUnitDefinition;
    ServiceIdentity();

    // Same size as wrapped internal type.
    unsigned char data_[kServiceIdentitySize];
};

// Size of internal record wrapped by UnitIdentifier.
// TODO(369534765) - Create and autogenerated constant for internal record size.
static const size_t kUnitIdentifierSize = 424;

/*  Defines an identifier used to uniquely identify a Service Unit.
 *  The Unit Identifier consists of the following components:
 *   1) Service Identity:  The identifier associated with the Service Bundle
 *          hosting the identified Service Unit.
 *   2) Unit Name: The Service Bundle specific name of the individual Service
 *          Unit being identified
 */
class UnitIdentifier {
public:
    // Copyable.
    UnitIdentifier(const UnitIdentifier&) = default;

    /**
     * Create a ServiceIdentity from its component fields.
     *
     * Parameters:
     *    [IN] service_identity
     *    [IN] unit_name
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a UnitIdentifier wrapper.
     */
    static SdvResult<UnitIdentifier> Create(const ServiceIdentity& service_identity,
                                            const std::string& unit_name);

    bool operator==(const UnitIdentifier& o) const;

    // Accessor for contained ServiceIdentity.
    // Returned reference has same lifetime as the UnitIdentifier.
    const ServiceIdentity& service_identity() const;

    // Accessor for contained Unit Name.
    // Returned pointer has same lifetime as the UnitIdentifier.
    std::string_view unit_name() const;

private:
    friend class sd::ServiceUnitDefinition;
    UnitIdentifier();

    // Same size as wrapped internal type
    unsigned char data_[kUnitIdentifierSize];
};

