// Size of internal struct contained by UnitType.
// TODO(369534765) - Create and autogenerated constant for internal record size.
static const size_t kUnitTypeSize = 272;

/*  Defines a Unit Type.
 *
 *  This name comprises the following components:
 *   1) SDV Package Name: The Package Name of the Service Bundle owning the UnitType.
 *   2) Service Bundle Name: The name of the Service Bundle that owns the Unit Type.
 *   3) Unit Type Name: The Unit Type Name as declared in the Service Bundle definition.
 */
class UnitType {
public:
    // Copyable.
    UnitType(const UnitType&) = default;

    /**
     * Create a UnitType from its human-readable string representation.
     *
     * Parameters:
     *    [IN] unit_type_str: String representation of UnitType to be parsed.
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a valid UnitType.
     */
    static sdv::SdvResult<UnitType> FromString(const std::string& unit_type_str);

    /**
     * Create a UnitType from its component fields.
     *
     * Each component has a length limit, given below.
     *
     * Parameters:
     *    [IN] sdv_package_name: 127 char max.
     *    [IN] service_bundle_name: 47 character max.
     *    [IN] unit_type_name: Number 47 character max.
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a valid UnitType.
     */
    static sdv::SdvResult<UnitType> Create(const std::string& sdv_package_name,
                                           const std::string& service_bundle_name,
                                           const std::string& unit_type_name);

    // Checks that the UnitType is populated with legal values.
    bool IsValid() const;

    // Produce a string representation of the UnitType.
    // This representation will be suitable for passing to FromString.
    std::string ToString() const;

    // Component accessors
    std::string_view sdv_package_name() const;
    std::string_view service_bundle_name() const;
    std::string_view unit_type_name() const;

private:
    friend class ServiceUnitDefinition;
    friend class UnitRegistrationArgs;

    // Note: Default-constructed UnitType is invalid.
    UnitType();

    // Size of wrapped record.
    unsigned char data_[kUnitTypeSize];
};

