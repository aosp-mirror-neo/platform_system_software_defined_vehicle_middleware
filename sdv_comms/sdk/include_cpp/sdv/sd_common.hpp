// Size of internal record wrapped by UnitNameDiscoveryArgs.
// TODO(369534765) - Create and autogenerated constant for internal record size.
static const size_t kUnitNameDiscoveryArgsSize = 336;

/**
 * Describes the arguments for Service Unit discovery by name..
 *
 * These arguments comprises the following components:
 * 1) [REQUIRED] SDV Package Name: The Package Name within which the Service Bundle was shipped.
 * 2) [REQUIRED] Service Bundle Name: The Service Bundle Name as declared in the Package Manifest.
 * 3) [OPTIONAL] Service Unit Name: The Service Unit Name as assigned by the Orchestrator
 *    when the Service Bundle was loaded. This value may be empty.
 * 4) [OPTIONAL] SDV VM Name: The SDV VM Instance on which this Service is registered. This value
 *    may be empty.
 *
 * [Service Naming Conventions]
 * (https://androidpartner.devsite.corp.google.com/automotive/sdv/core-areas/naming-conventions)
 */
class UnitNameDiscoveryArgs {
public:
    // Copyable.
    UnitNameDiscoveryArgs(const UnitNameDiscoveryArgs&) = default;

    /**
     * Create a UnitNameDiscoveryArgs from its component fields.
     *
     * Each component has a length limit, given below; given limits do not
     * include the NUL terminator.
     *
     * Parameters:
     *    [IN] sdv_package_name: 127 char max.
     *    [IN] service_bundle_name: 47 character max.
     *    [IN] unit_name: 31 character max.
     *    [IN] sdv_vm_name: 31 character max.
     *
     * Return value:
     *    SdvResult that contains SdvStatus of the method call and, if
     *    method succeeded, a UnitNameDiscoveryArgs wrapper.
     */
    static sdv::SdvResult<UnitNameDiscoveryArgs> Create(const std::string& sdv_package_name,
                                                        const std::string& service_bundle_name,
                                                        const std::string& unit_name = "",
                                                        const std::string& sdv_vm_name = "");

    // Component accessors
    std::string_view sdv_package_name() const;
    std::string_view service_bundle_name() const;

    // If unit_name or sdv_vm_name is unset, these return empty strings.
    std::string_view unit_name() const;
    std::string_view sdv_vm_name() const;

private:
    UnitNameDiscoveryArgs();

    unsigned char data_[kUnitNameDiscoveryArgsSize];
};

// Inferred metadata for a service unit
class InferredMetadata {
public:
    // Movable, not copyable.
    InferredMetadata(InferredMetadata&&);
    InferredMetadata(const InferredMetadata&) = delete;

    // Destructor to clean up underlying record.
    ~InferredMetadata();

    // Test whether the wrapper owns a reference to an internal object.
    bool IsValid() const;

    /// Location of a service unit relative to the caller of the API.
    enum class RelativeLocation { Unknown, LocalSdvInstance, LocalHardware, Remote };

    // Get the location of the service unit relative to the caller.
    RelativeLocation GetLocation() const;

    // Only public for testing purposes.
    static InferredMetadata Create();

private:
    friend ServiceUnitDefinition;

    InferredMetadata(ASDV_InferredMetadata*);
    InferredMetadata() = delete;

    ASDV_InferredMetadata* ToMutableABIPtr();

    // Pointer to owned underlying data.
    ASDV_InferredMetadata* handle_ = nullptr;
};

// Definition of a single Service Unit returned by a discovery operation.
class ServiceUnitDefinition {
public:
    // Copyable and movable.
    ServiceUnitDefinition(const ServiceUnitDefinition&);
    ServiceUnitDefinition(ServiceUnitDefinition&&);

    // Destructor to clean up underlying record.
    ~ServiceUnitDefinition();

    // Test whether the wrapper owns a reference to an internal object.
    bool IsValid() const;

    // Returns the UnitIdentifier for the Service Unit.
    id::UnitIdentifier GetUnitIdentifier() const;

    // Returns the UnitType for the Service Unit.
    UnitType GetUnitType() const;

    // Returns the identity for the bundle that registered the Service Unit.
    id::ServiceIdentity GetServiceBundleIdentity() const;

    // Returns the InferredMetadata for the Service Unit.
    InferredMetadata GetInferredMetadata() const;

    // Returns the UnitMetadata for the Service Unit.
    // May return std::monostate if no Server or Publisher metadata is
    // available for the Service Unit.
    UnitMetadata GetUnitMetadata() const;

    // Returns the Application Metadata for the Service Unit.
    std::vector<uint8_t> GetApplicationMetadata() const;

    // Get the ServerUnitMetadata for the Service Unit.
    // Returned object could be unpopulated; use IsValid() to check.
    ServerUnitMetadata GetServerUnitMetadata() const;

    // Get the PublisherUnitMetadata for the Service Unit.
    // Returned object could be unpopulated; use IsValid() to check.
    PublisherUnitMetadata GetPublisherUnitMetadata() const;

private:
    friend ServiceDiscoveryManager;
    friend ServiceUnitChangeListener;

    ServiceUnitDefinition(ASDV_ServiceUnitDefinition*);
    ServiceUnitDefinition() = delete;

    static ServiceUnitDefinition FromABIPtr(ASDV_ServiceUnitDefinition*);

    // Pointer to owned underlying data.
    ASDV_ServiceUnitDefinition* handle_ = nullptr;
};

