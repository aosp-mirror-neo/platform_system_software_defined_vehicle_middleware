//! Middleware RPC Traits

use async_trait::async_trait;
use futures::Stream;
use mockall::automock;
use sdv_status_rs::SdvResult;
use std::pin::Pin;

/// RPC client transport that makes RPC calls.
///
/// Intented to be implemented as part of the library code that does RPC integration. Is not exposed by autogenerated middleware code.
#[automock]
#[async_trait]
pub trait ClientTransport: Send + Sync {
    /// Calls a method with method name and request bytes.
    async fn call_method(&self, method: &str, request: &[u8]) -> SdvResult<Vec<u8>>;
    /// Calls a method with method name and request bytes using client streaming
    async fn call_client_streaming_method(
        &self,
        method_name: &str,
        request_stream: Pin<Box<dyn Stream<Item = Vec<u8>> + Send>>,
    ) -> SdvResult<Vec<u8>>;
    /// Calls a method with method name and request bytes using server streaming
    async fn call_server_streaming_method(
        &self,
        method_name: &str,
        request: &[u8],
    ) -> SdvResult<Pin<Box<dyn Stream<Item = SdvResult<Vec<u8>>> + Send>>>;
}

/// RPC server transport that serves methods over RPC.
///
/// An object that holds a handle to a server object and is threadsafe. Is not exposed by autogenerated middleware code.
pub trait ServerTransport: Send + Sync {}

/// Trait for a generated clients
pub trait RpcClient {
    /// yes
    const DEFAULT_UNIT_NAME: &'static str;
    /// yes
    fn new(transport: Box<dyn ClientTransport>) -> Self;
}
