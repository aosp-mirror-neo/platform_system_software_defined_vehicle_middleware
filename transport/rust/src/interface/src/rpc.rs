/// Calls a method with method name and RequestType message.
pub async fn call_method<RequestType: Message, ResponseType: Message>(
    client: &dyn ClientTransport,
    method: &str,
    request: &RequestType,
) -> SdvResult<ResponseType> {
    let request_bytes = request.write_to_bytes().map_err(|_| {
        SdvStatus::with_message(SdvStatusCode::InvalidArgument, "Failed to serialize request")
    })?;
    client.call_method(method, &request_bytes).await.map(|bytes| {
        ResponseType::parse_from_bytes(&bytes).map_err(|_| {
            SdvStatus::with_message(SdvStatusCode::Internal, "Failed to deserialize response")
        })
    })?
}

/// Calls a method with method name and RequestType message using client streaming.
pub async fn call_client_streaming_method<RequestType: Message, ResponseType: Message>(
    client: &dyn ClientTransport,
    method: &str,
    request: Pin<Box<dyn Stream<Item = RequestType> + Send>>,
) -> SdvResult<ResponseType> {
    // Create a TryStream that serializes each item. An error during serialization
    // will be propagated as an Err item in the stream.
    let try_stream = request.map(|request| {
        request.write_to_bytes().map_err(|_| {
            SdvStatus::with_message(SdvStatusCode::InvalidArgument, "Failed to serialize request")
        })
    });

    // A channel forwards successfully serialized bytes to the RPC call,
    // while allowing us to intercept a serialization error from the stream.
    let (tx, rx) = mpsc::channel::<Vec<u8>>(1);

    // The RPC call consumes from the receiver end of the channel.
    let rpc_call = client.call_client_streaming_method(method, rx.boxed());

    // Create a sink that maps channel errors to SdvStatus.
    let sink = tx.sink_map_err(|e| {
        SdvStatus::with_cause_and_message(
            SdvStatusCode::Cancelled,
            e,
            "RPC call terminated prematurely.",
        )
    });

    // The `forwarder` future consumes the `try_stream` and sends items to the sink.
    // `forward` on a `TryStream` stops on the first `Err` from either the stream or the sink.
    let forwarder = try_stream.forward(sink);

    let process_response = |bytes: Vec<u8>| {
        ResponseType::parse_from_bytes(&bytes).map_err(|_| {
            SdvStatus::with_message(SdvStatusCode::Internal, "Failed to deserialize response")
        })
    };

    // Race the forwarder and the rpc_call.
    match future::select(Box::pin(forwarder), Box::pin(rpc_call)).await {
        Either::Left((forwarder_result, rpc_call_rem)) => {
            // Forwarding finished, now wait for the final response.
            forwarder_result?;
            rpc_call_rem.await.and_then(process_response)
        }
        Either::Right((rpc_result, _forwarder_rem)) => {
            // RPC call finished before forwarding was complete (e.g. server error).
            rpc_result.and_then(process_response)
        }
    }
}

/// Calls a method with method name and RequestType message using server streaming.
pub async fn call_server_streaming_method<RequestType: Message, ResponseType: Message>(
    client: &dyn ClientTransport,
    method: &str,
    request: &RequestType,
) -> SdvResult<Pin<Box<dyn Stream<Item = SdvResult<ResponseType>> + Send>>> {
    let request_bytes = request.write_to_bytes().map_err(|_| {
        SdvStatus::with_message(SdvStatusCode::InvalidArgument, "Failed to serialize request")
    })?;
    client.call_server_streaming_method(method, &request_bytes).await.map(|stream_of_bytes| {
        stream_of_bytes
            .map(|bytes_result| {
                bytes_result.and_then(|bytes| {
                    ResponseType::parse_from_bytes(&bytes).map_err(|_| {
                        SdvStatus::with_message(
                            SdvStatusCode::Internal,
                            "Failed to deserialize stream response",
                        )
                    })
                })
            })
            .boxed()
    })
}

/// Builder struct to obtain a typeless method map from a proto-based method map.
#[derive(Default)]
pub struct MethodMapBuilder {
    #[deprecated(since = "2.0.0", note = "please use `rpc_methods` instead")]
    methods: HashMap<String, UnaryRpcMethod>,
    rpc_methods: HashMap<String, RpcMethod>,
}

impl MethodMapBuilder {
    /// New instance of the MethodMapBuilder.
    pub fn new() -> Self {
        Self { methods: HashMap::new(), rpc_methods: HashMap::new() }
    }

    /// Returns the RPC unary method map, consumes the builder.
    #[deprecated(since = "2.0.0", note = "please use `build_rpc_methods` instead")]
    pub fn build(self) -> HashMap<String, UnaryRpcMethod> {
        self.methods
    }

    /// Returns the map of all RPC methods (including unary, client streaming, and server streaming)
    /// consumes the builder.
    pub fn build_rpc_methods(self) -> HashMap<String, RpcMethod> {
        self.rpc_methods
    }

    /// Serves a unary method with method name, RequestType message and ResponseType message.
    pub fn add_method<RequestType: Message, ResponseType: Message>(
        mut self,
        method_name: &str,
        callback: Arc<
            dyn Fn(
                    ServiceFqin,
                    RequestType,
                ) -> Pin<Box<dyn Future<Output = SdvResult<ResponseType>> + Send>>
                + Send
                + Sync,
        >,
    ) -> Self {
        // Converts the proto-typed callback to a callback processing byte arrays.
        let typeless_callback: UnaryRpcMethod =
            Arc::new(move |service_fqin, request_bytes: &[u8]| {
                let callback = callback.clone();
                let request_bytes = request_bytes.to_vec();
                Box::pin({
                    async move {
                        let request =
                            RequestType::parse_from_bytes(&request_bytes).map_err(|_| {
                                SdvStatus::with_message(
                                    SdvStatusCode::InvalidArgument,
                                    "Failed to deserialize request",
                                )
                            })?;

                        callback(service_fqin, request).await?.write_to_bytes().map_err(|_| {
                            SdvStatus::with_message(
                                SdvStatusCode::Internal,
                                "Failed to serialize response",
                            )
                        })
                    }
                })
            });
        self.methods.insert(method_name.to_string(), typeless_callback.clone());
        self.rpc_methods
            .insert(method_name.to_string(), sdv_comms::rpc::RpcMethod::Unary(typeless_callback));
        self
    }

    /// Serves a server streaming method with method name, RequestType message and ResponseType message.
    pub fn add_server_streaming_method<
        RequestType: Message,
        ResponseType: Message + Send + 'static,
    >(
        mut self,
        method_name: &str,
        callback: Arc<
            dyn Fn(
                    ServiceFqin,
                    RequestType,
                ) -> Pin<
                    Box<
                        dyn Future<
                                Output = SdvResult<
                                    Pin<Box<dyn Stream<Item = SdvResult<ResponseType>> + Send>>,
                                >,
                            > + Send,
                    >,
                > + Send
                + Sync,
        >,
    ) -> Self {
        let typeless_callback: ServerStreamingRpcMethod =
            Arc::new(move |service_fqin, request_bytes: &[u8]| {
                let callback = callback.clone();
                let request_bytes = request_bytes.to_vec();
                Box::pin(async move {
                    let request = RequestType::parse_from_bytes(&request_bytes).map_err(|_| {
                        SdvStatus::with_message(
                            SdvStatusCode::InvalidArgument,
                            "Failed to deserialize request",
                        )
                    })?;
                    let stream_of_responses = callback(service_fqin, request).await?;
                    let stream_of_bytes: Pin<Box<dyn Stream<Item = SdvResult<Vec<u8>>> + Send>> =
                        Box::pin(stream_of_responses.map(|response_result| {
                            response_result.and_then(|response| {
                                response.write_to_bytes().map_err(|_| {
                                    SdvStatus::with_message(
                                        SdvStatusCode::Internal,
                                        "Failed to serialize stream response",
                                    )
                                })
                            })
                        }));
                    Ok(stream_of_bytes)
                })
            });
        self.rpc_methods.insert(
            method_name.to_string(),
            sdv_comms::rpc::RpcMethod::ServerStreaming(typeless_callback),
        );
        self
    }

    /// Serves a client streaming method with method name, RequestType message and ResponseType message.
    pub fn add_client_streaming_method<
        RequestType: Message + Send + 'static,
        ResponseType: Message,
    >(
        mut self,
        method_name: &str,
        callback: Arc<
            dyn Fn(
                    ServiceFqin,
                    Pin<Box<dyn Stream<Item = RequestType> + Send>>,
                ) -> Pin<Box<dyn Future<Output = SdvResult<ResponseType>> + Send>>
                + Send
                + Sync,
        >,
    ) -> Self {
        let typeless_callback: ClientStreamingRpcMethod =
            Arc::new(move |service_fqin, request_stream_of_bytes| {
                let callback = callback.clone();
                Box::pin(async move {
                    // Create a channel for deserialized messages.
                    let (tx, rx) = mpsc::channel::<RequestType>(1);

                    // This is the stream of deserialized messages we'll pass to the user's callback.
                    let request_stream = rx.boxed();

                    // Call the user's callback. This gives us a future for the response.
                    let response_future = callback(service_fqin, request_stream);

                    // Create a stream that deserializes bytes into messages.
                    let deserializing_stream = request_stream_of_bytes
                        .map_err(|status| {
                            SdvStatus::with_cause_and_message(
                                SdvStatusCode::from(status.code() as i32),
                                status,
                                "Error in client stream",
                            )
                        })
                        .and_then(|bytes| async move {
                            RequestType::parse_from_bytes(&bytes).map_err(|e| {
                                SdvStatus::with_cause_and_message(
                                    SdvStatusCode::InvalidArgument,
                                    e,
                                    "Failed to deserialize stream request",
                                )
                            })
                        });

                    // Create a sink that maps channel errors to SdvStatus.
                    let sink = tx.sink_map_err(|e| {
                        SdvStatus::with_cause_and_message(
                            SdvStatusCode::Cancelled,
                            e,
                            "Callback processing terminated prematurely.",
                        )
                    });

                    // The `forwarder` future consumes the `deserializing_stream` and sends items to the sink.
                    let forwarder = deserializing_stream.forward(sink);

                    let process_response = |response: ResponseType| {
                        response.write_to_bytes().map_err(|_| {
                            SdvStatus::with_message(
                                SdvStatusCode::Internal,
                                "Failed to serialize response",
                            )
                        })
                    };

                    // Race the forwarder and the response_future.
                    match future::select(Box::pin(forwarder), Box::pin(response_future)).await {
                        Either::Left((forwarder_result, response_future_rem)) => {
                            // Forwarding finished, now wait for the final response.
                            forwarder_result?;
                            response_future_rem.await.and_then(process_response)
                        }
                        Either::Right((response_result, _forwarder_rem)) => {
                            // RPC call finished before forwarding was complete (e.g. server error).
                            response_result.and_then(process_response)
                        }
                    }
                })
            });
        self.rpc_methods.insert(
            method_name.to_string(),
            sdv_comms::rpc::RpcMethod::ClientStreaming(typeless_callback),
        );
        self
    }
}

