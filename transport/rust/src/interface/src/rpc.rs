    fn create_uninitialized_field_descriptor_proto() -> FieldDescriptorProto {
        let uninitialized_name_part = protobuf::descriptor::uninterpreted_option::NamePart::new();

        let mut uninterpreted_option = UninterpretedOption::new();
        uninterpreted_option.name.push(uninitialized_name_part);

        let mut field_options = FieldOptions::new();
        field_options.uninterpreted_option.push(uninterpreted_option);

        let mut field_descriptor_proto = FieldDescriptorProto::new();
        field_descriptor_proto.options = protobuf::MessageField::some(field_options);
        field_descriptor_proto
    }

