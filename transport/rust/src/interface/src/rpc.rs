    #[tokio::test]
    async fn test_method_map_builder_add_method() {
        // GIVEN a method name and a typed callback
        let method_name = "MyTestMethod";
        let bundle_name: &str = "RpcBundle";
        let test_fqin =
            ServiceFqin::from_str(&format!("{VM}:{PACKAGE}.{bundle_name}/sample")).unwrap();

        let typed_callback = Arc::new(
            move |_fqin: ServiceFqin,
                  req: StringValue|
                  -> Pin<Box<dyn Future<Output = SdvResult<StringValue>> + Send>> {
                let mut response = StringValue::new();
                response.value = format!("Response to: {}", req.value);
                Box::pin(async move { Ok(response) })
            },
        );

        // WHEN a method is added using MethodMapBuilder
        let builder = MethodMapBuilder::new();
        assert_eq!(builder.methods.len(), 0);
        let method_map = builder.add_method(method_name, typed_callback).build();

        // THEN the method map contains the typeless callback
        assert_eq!(method_map.len(), 1);
        let typeless_callback = method_map.get(method_name).unwrap();

        // WHEN the typeless callback is invoked with invalid request bytes
        let invalid_request_bytes = vec![0x0A, 0x01, 0xFF]; // Invalid protobuf bytes
        let response_future_invalid = typeless_callback(test_fqin.clone(), &invalid_request_bytes);
        let response_result_invalid = response_future_invalid.await;

        // THEN the result is err
        assert!(response_result_invalid.is_err());
        let result_err = response_result_invalid.unwrap_err();
        assert_eq!(result_err.status_code(), SdvStatusCode::InvalidArgument);
        assert_eq!(
            result_err.to_string(),
            "SdvStatusCode::InvalidArgument(3): Failed to deserialize request"
        );

        // AND WHEN the typeless callback is invoked with serialized request
        let mut request_msg = StringValue::new();
        request_msg.value = "hello_rpc".to_string();
        let request_bytes = request_msg.write_to_bytes().unwrap();

        let response_future = typeless_callback(test_fqin.clone(), &request_bytes);
        let response_result_bytes = response_future.await;

        // THEN the original typed callback was called and the response is correct
        assert!(response_result_bytes.is_ok());
        let response_bytes = response_result_bytes.unwrap();
        let response_msg = StringValue::parse_from_bytes(&response_bytes).unwrap();
        assert_eq!(response_msg.value, "Response to: hello_rpc");
    }

